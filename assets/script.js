// Mobile Menu - SIMPLE & FUNCTIONAL
document.addEventListener('DOMContentLoaded', () => {
  const toggle = document.getElementById('mobile-menu-toggle');
  const menu = document.getElementById('mobile-menu');
  const overlay = document.getElementById('mobile-menu-overlay');
  const links = document.querySelectorAll('.mobile-menu-link');
  const mobileDropdowns = document.querySelectorAll('.mobile-nav-item-dropdown');

  function closeMobileMenu() {
    if (toggle) toggle.classList.remove('active');
    if (menu) {
      menu.classList.remove('active');
      menu.classList.remove('from-bottom');
    }
    if (overlay) overlay.classList.remove('active');
    if (toggle) toggle.setAttribute('aria-expanded', 'false');

    mobileDropdowns.forEach(d => {
      d.classList.remove('is-open');
      const tr = d.querySelector('.mobile-dropdown-trigger');
      if (tr) tr.setAttribute('aria-expanded', 'false');
    });
  }

  // Toggle menu desde navbar (arriba a la izquierda)
  if (toggle && menu) {
    toggle.addEventListener('click', (e) => {
      if (e) {
        e.preventDefault();
        e.stopPropagation();
      }
      const isCurrentlyFromBottom = menu.classList.contains('from-bottom');
      menu.classList.remove('from-bottom');

      const isOpen = isCurrentlyFromBottom ? true : menu.classList.toggle('active');
      if (isCurrentlyFromBottom) menu.classList.add('active');

      toggle.classList.toggle('active', isOpen);
      if (overlay) overlay.classList.toggle('active', isOpen);
      toggle.setAttribute('aria-expanded', isOpen ? 'true' : 'false');
    });
  }

  // Toggle menu desde barra móvil inferior (justo encima del botón de la barra)
  const bottomMenuBtn = document.getElementById('btnToggleSectionsPopup');
  if (bottomMenuBtn && menu) {
    bottomMenuBtn.addEventListener('click', (e) => {
      if (e) {
        e.preventDefault();
        e.stopPropagation();
      }
      const isAlreadyFromBottom = menu.classList.contains('from-bottom') && menu.classList.contains('active');
      if (isAlreadyFromBottom) {
        closeMobileMenu();
      } else {
        menu.classList.add('from-bottom');
        menu.classList.add('active');
        if (toggle) toggle.classList.add('active');
        if (overlay) overlay.classList.remove('active');
        if (toggle) toggle.setAttribute('aria-expanded', 'true');
      }
    });
  }

  // Manejador interactivo de submenús en móvil (Touch & Click)
  mobileDropdowns.forEach(dropdown => {
    const trigger = dropdown.querySelector('.mobile-dropdown-trigger');
    if (!trigger) return;

    trigger.addEventListener('click', (e) => {
      e.preventDefault();
      e.stopPropagation();

      const wasOpen = dropdown.classList.contains('is-open');

      if (wasOpen) {
        // Cierra y previene que el hover lo vuelva a abrir de inmediato
        dropdown.classList.remove('is-open');
        trigger.setAttribute('aria-expanded', 'false');
        dropdown.classList.add('prevent-hover');
      } else {
        dropdown.classList.add('is-open');
        dropdown.classList.remove('prevent-hover');
        trigger.setAttribute('aria-expanded', 'true');
      }

      // Cerrar otros dropdowns móviles si hubiera más de uno
      mobileDropdowns.forEach(other => {
        if (other !== dropdown) {
          other.classList.remove('is-open');
          const otherTr = other.querySelector('.mobile-dropdown-trigger');
          if (otherTr) otherTr.setAttribute('aria-expanded', 'false');
        }
      });
    });

    dropdown.addEventListener('mouseleave', () => {
      dropdown.classList.remove('prevent-hover');
    });
  });

  // Close menu on overlay click
  if (overlay) {
    overlay.addEventListener('click', closeMobileMenu);
  }

  // Close menu on link click
  links.forEach(link => {
    link.addEventListener('click', closeMobileMenu);
  });

  // Close menu on Escape
  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape' && menu && menu.classList.contains('active')) {
      closeMobileMenu();
    }
  });

  // Close menu when clicking outside (salvo clics en los botones toggle o dentro del menú)
  document.addEventListener('click', (e) => {
    if (menu && menu.classList.contains('active') &&
        !e.target.closest('#mobile-menu') &&
        !e.target.closest('#mobile-menu-toggle') &&
        !e.target.closest('#btnToggleSectionsPopup')) {
      closeMobileMenu();
    }
  });

  // Sincronización interactiva de los puntos del carrusel de Instagram
  const postsTrack = document.querySelector('.posts');
  const postDots = Array.from(document.querySelectorAll('.posts-dot'));
  if (postsTrack && postDots.length > 0) {
    const postCards = Array.from(postsTrack.querySelectorAll('.post'));

    function goToPost(index) {
      const target = postCards[index];
      if (!target) return;
      postsTrack.scrollTo({ left: target.offsetLeft - 16, behavior: 'smooth' });
    }

    postDots.forEach((dot, index) => {
      dot.addEventListener('click', () => goToPost(index));
    });

    let postsRaf = false;
    postsTrack.addEventListener('scroll', () => {
      if (postsRaf) return;
      postsRaf = true;
      requestAnimationFrame(() => {
        const scrollPos = postsTrack.scrollLeft;
        let closestIndex = 0;
        let minDiff = Infinity;
        postCards.forEach((card, i) => {
          const diff = Math.abs(card.offsetLeft - 16 - scrollPos);
          if (diff < minDiff) {
            minDiff = diff;
            closestIndex = i;
          }
        });
        postDots.forEach((dot, i) => {
          const isActive = i === closestIndex;
          dot.classList.toggle('active', isActive);
          dot.setAttribute('aria-selected', isActive ? 'true' : 'false');
        });
        postsRaf = false;
      });
    }, { passive: true });
  }

  // Simulación interactiva de WhatsApp en bucle continuo y sincronizado
  const heroChat = document.getElementById('heroChatContainer');
  const typingBubble = document.getElementById('heroTypingBubble');

  if (heroChat) {
    const msgs = Array.from(heroChat.querySelectorAll('.wa, .wa-sys'));
    let simTimeouts = [];

    function clearSimTimeouts() {
      simTimeouts.forEach(t => clearTimeout(t));
      simTimeouts = [];
    }

    let isLoopRunning = false;

    function startLoop() {
      if (!isLoopRunning && document.visibilityState !== 'hidden') {
        isLoopRunning = true;
        runHeroChatLoop();
      }
    }

    function stopLoop() {
      isLoopRunning = false;
      clearSimTimeouts();
    }

    function runHeroChatLoop() {
      clearSimTimeouts();
      if (!isLoopRunning || document.visibilityState === 'hidden') return;

      // Ocultar todos los mensajes al inicio del ciclo
      msgs.forEach(m => {
        m.style.opacity = '0';
        m.style.transform = 'translateY(8px)';
        m.style.transition = 'opacity 0.35s ease, transform 0.35s cubic-bezier(0.16, 1, 0.3, 1)';
      });
      if (typingBubble) {
        typingBubble.style.display = 'none';
        typingBubble.style.opacity = '0';
      }

      // 1. Entra mensaje del cliente
      simTimeouts.push(setTimeout(() => {
        if (msgs[0]) {
          msgs[0].style.opacity = '1';
          msgs[0].style.transform = 'translateY(0)';
        }
      }, 500));

      // 2. Aparecen los 3 puntos ("escribiendo...")
      simTimeouts.push(setTimeout(() => {
        if (typingBubble) {
          typingBubble.style.display = 'inline-flex';
          requestAnimationFrame(() => typingBubble.style.opacity = '1');
        }
      }, 1400));

      // 3. Tras 3 segundos de escritura, desaparecen los puntos y entra la respuesta del bot
      simTimeouts.push(setTimeout(() => {
        if (typingBubble) typingBubble.style.display = 'none';
        if (msgs[1]) {
          msgs[1].style.opacity = '1';
          msgs[1].style.transform = 'translateY(0)';
        }
      }, 4400));

      // 4. Mensaje de confirmación del cliente
      simTimeouts.push(setTimeout(() => {
        if (msgs[2]) {
          msgs[2].style.opacity = '1';
          msgs[2].style.transform = 'translateY(0)';
        }
      }, 5600));

      // 5. Confirmación del sistema Calendar
      simTimeouts.push(setTimeout(() => {
        if (msgs[3]) {
          msgs[3].style.opacity = '1';
          msgs[3].style.transform = 'translateY(0)';
        }
      }, 6600));

      // 6. Pausa de lectura breve (~2.6s) y reiniciar el bucle si sigue activo y visible
      simTimeouts.push(setTimeout(() => {
        if (isLoopRunning && document.visibilityState !== 'hidden') {
          runHeroChatLoop();
        }
      }, 9200));
    }

    // Escuchar cambios de visibilidad de pestaña para ahorrar ciclos de CPU
    document.addEventListener('visibilitychange', () => {
      if (document.visibilityState === 'hidden') {
        stopLoop();
      } else {
        startLoop();
      }
    });

    // Iniciar bucle inicial
    startLoop();
  }
});
