  let lastScrollY = window.scrollY;
  window.addEventListener('scroll', () => {
    if (!scrollRaf) {
      requestAnimationFrame(() => {
        const currentY = window.scrollY;
        if (btnScrollTop) {
          if (currentY > 300) {
            btnScrollTop.classList.add('visible');
          } else {
            btnScrollTop.classList.remove('visible');
          }
        }
        if (mobileBar) {
          if (currentY > 200) {
            mobileBar.classList.add('visible');
            if (currentY - lastScrollY > 10 && currentY > 500) {
              mobileBar.classList.add('hidden-by-scroll');
              if (btnScrollTop) btnScrollTop.style.bottom = '16px';
            } else if (lastScrollY - currentY > 10) {
              mobileBar.classList.remove('hidden-by-scroll');
              if (btnScrollTop) btnScrollTop.style.bottom = '74px';
            }
          } else {
            mobileBar.classList.remove('visible');
            mobileBar.classList.remove('hidden-by-scroll');
            if (btnScrollTop) btnScrollTop.style.bottom = '74px';
          }
        }
        lastScrollY = currentY;
        scrollRaf = false;
      });
      scrollRaf = true;
    }
  }, { passive: true });