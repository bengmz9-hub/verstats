  function closeMobileMenu() {
    if (toggleBtn) toggleBtn.classList.remove('active');
    if (menu) {
      menu.classList.remove('active');
      menu.classList.remove('from-bottom');
    }
    if (overlay) overlay.classList.remove('active');
    if (toggleBtn) toggleBtn.setAttribute('aria-expanded', 'false');

    mobileDropdowns.forEach(d => {
      d.classList.remove('is-open');
      const tr = d.querySelector('.mobile-dropdown-trigger');
      if (tr) tr.setAttribute('aria-expanded', 'false');
    });
  }

  if (toggleBtn && menu) {
    toggleBtn.addEventListener('click', (e) => {
      e.preventDefault();
      e.stopPropagation();
      const isFromBottom = menu.classList.contains('from-bottom');
      menu.classList.remove('from-bottom');
      const isOpen = isFromBottom ? true : menu.classList.toggle('active');
      if (isFromBottom) menu.classList.add('active');
      toggleBtn.classList.toggle('active', isOpen);
      if (overlay) overlay.classList.toggle('active', isOpen);
      toggleBtn.setAttribute('aria-expanded', isOpen ? 'true' : 'false');
    });
  }

  if (bottomMenuBtn && menu) {
    bottomMenuBtn.addEventListener('click', (e) => {
      e.preventDefault();
      e.stopPropagation();
      const isAlreadyOpen = menu.classList.contains('from-bottom') && menu.classList.contains('active');
      if (isAlreadyOpen) {
        closeMobileMenu();
      } else {
        menu.classList.add('from-bottom');
        menu.classList.add('active');
        if (toggleBtn) toggleBtn.classList.add('active');
        if (overlay) overlay.classList.remove('active');
        if (toggleBtn) toggleBtn.setAttribute('aria-expanded', 'true');
      }
    });
  }

